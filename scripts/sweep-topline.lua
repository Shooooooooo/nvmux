-- Where Neovim's view goes when a motion takes the cursor past the edge of
-- 'scrolloff': the table `src/client/moves.rs` checks its `keep_in_view`
-- against (`motions_past_the_edges_scroll_as_neovim_does`).
--
--   nvim --clean -n --headless -c 'luafile scripts/sweep-topline.lua'
--
-- prints it as the Rust `const TOPLINE` that test pastes in. Run with
-- Neovim 0.12.6.
--
-- For every window height h from 4 to 60 and every 'scrolloff' from nought
-- to h/2, the cursor is put on the last row 'scrolloff' lets it be on —
-- the bottom one, less 'scrolloff', for a motion down; the top one, plus
-- it, for a motion up — of a view from line 400 of a buffer 1000 lines
-- long, and moved N lines, N from 1 to h, by `Nj`, `Ngj`, `Nk` and `Ngk`.
-- What is said of each is how far N goes with Neovim scrolling the view
-- just far enough to keep 'scrolloff' between the cursor and the edge — no
-- further, as `scroll_cursor_top` and `scroll_cursor_bot` do for a small
-- move — before it first does otherwise, centring the cursor as
-- `scroll_cursor_halfway` does: the first N it does otherwise, less one,
-- or h where it never does. Up, that is half the window less one, and
-- never under two, whatever 'scrolloff' is; down, further.

vim.o.lines = 100
vim.o.laststatus = 0
vim.o.cmdheight = 1
vim.o.more = false

local lines = {}
for i = 1, 1000 do
  lines[i] = 'line ' .. i
end
vim.cmd('new')
vim.api.nvim_buf_set_lines(0, 0, -1, false, lines)

local top = 400
local rows = {}
for h = 4, 60 do
  vim.api.nvim_win_set_height(0, h)
  assert(vim.api.nvim_win_get_height(0) == h, 'a window ' .. h .. ' rows tall')
  local runs = {}
  for _, key in ipairs({ 'j', 'gj', 'k', 'gk' }) do
    local run = {}
    for so = 0, math.floor(h / 2) do
      vim.wo.scrolloff = so
      local up = key:find('k') ~= nil
      local from = up and top + so or top + h - 1 - so
      local minimal = h
      for n = 1, h do
        vim.fn.winrestview({ topline = top + 1, lnum = from + 1, col = 0 })
        vim.cmd('redraw')
        local was = vim.fn.winsaveview()
        assert(was.topline == top + 1 and was.lnum == from + 1, 'the view to start from')
        vim.cmd('normal! ' .. n .. key)
        vim.cmd('redraw')
        local v = vim.fn.winsaveview()
        local cursor = v.lnum - 1
        local just = up and cursor - so or cursor + so - (h - 1)
        if v.topline - 1 ~= just then
          minimal = n - 1
          break
        end
      end
      run[#run + 1] = tostring(minimal)
    end
    runs[#runs + 1] = '        &[' .. table.concat(run, ', ') .. '],'
  end
  rows[#rows + 1] = string.format('    (%d, [\n%s\n    ]),', h, table.concat(runs, '\n'))
end
local v = vim.version()

io.stdout:write(table.concat({
  string.format('/// Generated by `scripts/sweep-topline.lua` with Neovim %d.%d.%d: for',
    v.major, v.minor, v.patch),
  '/// each window height, and for `j`, `gj`, `k` and `gk` in turn, how far a',
  "/// count goes, for each 'scrolloff' from nought to half the height, with",
  '/// Neovim scrolling the view no further than it must — the count before the',
  '/// first it scrolls further for, or the height where none is.',
  '#[rustfmt::skip]',
  'const TOPLINE: &[(i64, [&[i64]; 4])] = &[',
  table.concat(rows, '\n'),
  '];',
  '',
}, '\n'))
vim.cmd('qa!')
