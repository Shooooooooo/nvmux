//! The colours xterm knows by name.
//!
//! xterm takes a colour by name wherever it takes one — `xterm -fg
//! SteelBlue`, its `colorN` resources, an OSC 4 that sets one — and looks the
//! name up as every X client does, in X11's colour database: `rgb.txt`, which
//! X.Org's server has built in (`os/oscolor.c`) rather than reading it. This
//! is that table, so that `[theme] color` takes a name as xterm does (see
//! [`crate::config::ThemeColor`]).
//!
//! # As X spells them
//!
//! Each name is here once, as X spells it with no spaces: `SteelBlue`,
//! `gray50`. X lists a name of more than one word twice, with its spaces and
//! without — `steel blue` and `SteelBlue` — and finds either in any case.
//! [`colour`] finds a name in any case, with or without its spaces: every
//! spelling X takes, and a few it does not, `steel blue1`, that can mean no
//! other colour.
//!
//! # X11's colours, not the web's
//!
//! CSS took its colour names from X11, and four of them came out different:
//! X's `gray` is `#bebebe`, its `green` `#00ff00`, its `maroon` `#b03060` and
//! its `purple` `#a020f0`, where the web's are `#808080`, `#008000`,
//! `#800000` and `#800080`. These are X's, which are what xterm draws; the
//! web's four are here as X has them too, `WebGray`, `WebGreen`, `WebMaroon`
//! and `WebPurple`.
//!
//! # A name is not the terminal's colour
//!
//! A name is one colour whatever the terminal is. `red` is `#ff0000`, which
//! is xterm's bright red: the red a program asks a terminal for, colour 1, is
//! xterm's `red3`, and on any other terminal whatever it says. xterm's own
//! sixteen are names but for one ([`crate::palette::XTERM_ANSI`]).

use crate::palette::Rgb;

/// The colour xterm knows by `name`, with its name as X spells it: in any
/// case, and with or without the spaces between its words — `SteelBlue`,
/// `steelblue` and `steel blue` are all `SteelBlue`. `None` for a name X does
/// not know.
pub fn colour(name: &str) -> Option<(&'static str, Rgb)> {
    NAMES.iter().copied().find(|(known, _)| same(known, name))
}

/// Whether `name` is `known`, case and spaces aside.
fn same(known: &str, name: &str) -> bool {
    let fold = |b: u8| b.to_ascii_lowercase();
    known
        .bytes()
        .map(fold)
        .eq(name.bytes().filter(|&b| b != b' ').map(fold))
}

